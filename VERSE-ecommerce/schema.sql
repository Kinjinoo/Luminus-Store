-- VÉRSE database setup for Supabase
-- Run the whole file in Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name) values(new.id, coalesce(new.raw_user_meta_data->>'full_name',''))
  on conflict(id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null,
 description text default '',
 price numeric(10,2) not null check(price>0),
 category text not null check(category in ('tops','bottoms','dresses','accessories')),
 image_url text not null,
 stock integer not null default 0 check(stock>=0),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id uuid primary key,
 user_id uuid not null references auth.users(id),
 customer_name text not null,
 phone text not null,
 email text,
 address text not null,
 subtotal numeric(10,2) not null,
 shipping numeric(10,2) not null,
 total numeric(10,2) not null,
 slip_path text not null,
 status text not null default 'รอตรวจสอบสลิป'
   check(status in ('รอตรวจสอบสลิป','ชำระเงินแล้ว','กำลังจัดส่ง','จัดส่งสำเร็จ','ยกเลิก')),
 created_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id uuid not null references public.orders(id) on delete cascade,
 product_id bigint references public.products(id),
 product_name text not null,
 unit_price numeric(10,2) not null,
 quantity integer not null check(quantity>0),
 size text
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create or replace function public.is_verse_admin()
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

drop policy if exists "profiles read own or admin" on public.profiles;
create policy "profiles read own or admin" on public.profiles for select to authenticated
using (id=auth.uid() or public.is_verse_admin());
drop policy if exists "products public read active" on public.products;
create policy "products public read active" on public.products for select to anon,authenticated
using (active=true or public.is_verse_admin());
drop policy if exists "products admin insert" on public.products;
create policy "products admin insert" on public.products for insert to authenticated with check(public.is_verse_admin());
drop policy if exists "products admin update" on public.products;
create policy "products admin update" on public.products for update to authenticated using(public.is_verse_admin()) with check(public.is_verse_admin());
drop policy if exists "products admin delete" on public.products;
create policy "products admin delete" on public.products for delete to authenticated using(public.is_verse_admin());

drop policy if exists "orders customer or admin read" on public.orders;
create policy "orders customer or admin read" on public.orders for select to authenticated using(user_id=auth.uid() or public.is_verse_admin());
drop policy if exists "orders admin update" on public.orders;
create policy "orders admin update" on public.orders for update to authenticated using(public.is_verse_admin()) with check(public.is_verse_admin());
drop policy if exists "items customer or admin read" on public.order_items;
create policy "items customer or admin read" on public.order_items for select to authenticated
using(exists(select 1 from public.orders o where o.id=order_id and (o.user_id=auth.uid() or public.is_verse_admin())));

-- Customers cannot directly insert orders/items. Use this validated RPC instead.
create or replace function public.place_verse_order(
 p_order_id uuid, p_items jsonb, p_slip_path text,
 p_customer_name text, p_phone text, p_email text, p_address text
) returns uuid language plpgsql security definer set search_path=public as $$
declare
 v_uid uuid := auth.uid();
 v_item jsonb;
 v_product public.products%rowtype;
 v_qty integer;
 v_subtotal numeric(10,2) := 0;
 v_shipping numeric(10,2);
 v_total numeric(10,2);
begin
 if v_uid is null then raise exception 'กรุณาเข้าสู่ระบบก่อนสั่งซื้อ'; end if;
 if length(trim(coalesce(p_customer_name,'')))<2 or length(trim(coalesce(p_phone,'')))<9 or length(trim(coalesce(p_address,'')))<8 then
   raise exception 'กรุณากรอกข้อมูลจัดส่งให้ครบถ้วน';
 end if;
 if p_slip_path not like v_uid::text || '/' || p_order_id::text || '/%' then
   raise exception 'เส้นทางไฟล์สลิปไม่ถูกต้อง';
 end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'ไม่มีสินค้าในคำสั่งซื้อ'; end if;

 -- Lock product rows while checking stock and calculate prices from DB (not browser).
 for v_item in select value from jsonb_array_elements(p_items) loop
   select * into v_product from public.products where id=(v_item->>'product_id')::bigint and active=true for update;
   if not found then raise exception 'พบสินค้าที่ไม่มีอยู่หรือปิดขาย'; end if;
   v_qty := (v_item->>'quantity')::integer;
   if v_qty<1 or v_qty>v_product.stock then raise exception 'สินค้า % มีสต็อกไม่เพียงพอ',v_product.name; end if;
   v_subtotal := v_subtotal + v_product.price*v_qty;
 end loop;
 v_shipping := case when v_subtotal>=1500 then 0 else 50 end;
 v_total := v_subtotal+v_shipping;

 insert into public.orders(id,user_id,customer_name,phone,email,address,subtotal,shipping,total,slip_path)
 values(p_order_id,v_uid,trim(p_customer_name),trim(p_phone),nullif(trim(p_email),''),trim(p_address),v_subtotal,v_shipping,v_total,p_slip_path);

 for v_item in select value from jsonb_array_elements(p_items) loop
   select * into v_product from public.products where id=(v_item->>'product_id')::bigint and active=true;
   v_qty := (v_item->>'quantity')::integer;
   insert into public.order_items(order_id,product_id,product_name,unit_price,quantity)
   values(p_order_id,v_product.id,v_product.name,v_product.price,v_qty);
   update public.products set stock=stock-v_qty where id=v_product.id;
 end loop;
 return p_order_id;
end; $$;
revoke all on function public.place_verse_order(uuid,jsonb,text,text,text,text,text) from public;
grant execute on function public.place_verse_order(uuid,jsonb,text,text,text,text,text) to authenticated;

-- Private bucket for payment slips (5 MB limit; image files only).
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('payment-slips','payment-slips',false,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=false,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "customer upload own slip" on storage.objects;
create policy "customer upload own slip" on storage.objects for insert to authenticated
with check(bucket_id='payment-slips' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "customer read own slip or admin" on storage.objects;
create policy "customer read own slip or admin" on storage.objects for select to authenticated
using(bucket_id='payment-slips' and ((storage.foldername(name))[1]=auth.uid()::text or public.is_verse_admin()));
drop policy if exists "customer delete own slip" on storage.objects;
create policy "customer delete own slip" on storage.objects for delete to authenticated
using(bucket_id='payment-slips' and (storage.foldername(name))[1]=auth.uid()::text);

